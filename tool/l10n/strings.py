def placeholders(text):
    # top-level {name} or {name, plural, ...}
    names, depth, i = [], 0, 0
    for m in re.finditer(r'[{}]', text):
        if m.group() == '{':
            if depth == 0:
                name = re.match(r'\{\s*(\w+)', text[m.start():]).group(1)
                if name not in names: names.append(name)
            depth += 1
        else:
            depth -= 1
    return names

for index, locale in enumerate(['en', 'uz', 'ru'], start=1):
    arb = {'@@locale': locale}
    for row in S:
        key, text = row[0], row[index]
        arb[key] = text
        if locale == 'en':
            names = placeholders(text)
            for other in row[2:]:
                for n in placeholders(other):
                    if n not in names:
                        raise SystemExit(f'{key}: {n} missing in English')
            if names:
                arb['@' + key] = {'placeholders': {
                    n: {'type': 'int' if n in INT_PLACEHOLDERS else 'String'}
                    for n in names}}
    with open(os.path.join(out_dir, f'app_{locale}.arb'), 'w', encoding='utf-8') as f:
        json.dump(arb, f, ensure_ascii=False, indent=2)
        f.write('\n')
